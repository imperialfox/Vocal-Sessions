#!/usr/bin/env node
/* Q24 coach video kit · build_data.js
   Builds data.js for the slide from:
     content.json            the approved wording (36 levels)
     data/audio_timeline.json pill states and rounds from the audio pass
     data/level_frames.json  the 36 level-start frames, measured from the original video
     ../../js/config.js      FOCUS_COL and GLYPH (tile colour and glyph, so the video matches the app)
     ../../css/app.css       light-theme values for any var(--…) colour
   Usage: node build_data.js [repoRoot]   (repoRoot defaults to ../..) */
const fs = require('fs'), path = require('path'), vm = require('vm');
const here = __dirname, root = path.resolve(process.argv[2] || path.join(here, '..', '..'));
const read = (p) => fs.readFileSync(p, 'utf8');

/* the app's FOCUS_COL and GLYPH, evaluated straight from config.js */
const cfg = vm.runInNewContext(read(path.join(root, 'js', 'config.js')) + ';({FOCUS_COL, GLYPH})', {});
/* light-theme custom properties: the first definition of each in app.css */
const css = read(path.join(root, 'css', 'app.css')), vars = {};
for (const m of css.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) if (!(m[1] in vars)) vars[m[1]] = m[2].trim();
const resolve = (v, n = 0) => {
  const m = /^var\((--[\w-]+)\)$/.exec(v.trim());
  if (!m) return v.trim().toUpperCase();
  if (n > 8 || !(m[1] in vars)) throw new Error('cannot resolve ' + v);
  return resolve(vars[m[1]], n + 1);
};
const glyphInner = (svg) => svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');

const content = JSON.parse(read(path.join(here, 'content.json')));
const tl = JSON.parse(read(path.join(here, 'data', 'audio_timeline.json'))).levels;
const lf = JSON.parse(read(path.join(here, 'data', 'level_frames.json')));
if (tl.length !== 36 || lf.level_start_frames.length !== 36) throw new Error('expected 36 levels');

const ex = content.exercises.map((e, i) => {
  const col = cfg.FOCUS_COL[e.focus];
  if (!col) throw new Error('no FOCUS_COL for ' + e.focus);
  if (!cfg.GLYPH[e.id]) throw new Error('no GLYPH for ' + e.id);
  return { id: e.id, name: e.name, rim: e.rim, tile: resolve(col), focus: e.focus, glyph: glyphInner(cfg.GLYPH[e.id]), syll: e.syll, lv: e.lv };
});
const levels = tl.map((l, i) => ({
  id: l.id, ex: Math.floor(i / 3), level: l.level, glide: l.glide,
  startFrame: lf.level_start_frames[i],
  states: l.states, rounds: l.rounds,
}));
levels.forEach((l, i) => { l.endFrame = i < 35 ? levels[i + 1].startFrame : lf.total_frames; });
const DATA = { fps: lf.fps, totalFrames: lf.total_frames, exercises: ex, levels };
fs.writeFileSync(path.join(here, 'data.js'), '/* generated by build_data.js — do not edit */\nwindow.DATA=' + JSON.stringify(DATA) + ';\n');
console.log('data.js written:', ex.map((e) => `${e.id} ${e.tile}`).join(', '));
