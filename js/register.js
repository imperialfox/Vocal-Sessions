/* Vocal Sessions · register.js (3.50, Q36)
   The screen register: every screen, sub-page, sheet and overlay the app can show, with a permanent ID (VS-001 onwards),
   its main parts' names, and the main journeys (flows, F-01 onwards). Plain data: nothing here runs.
   - render() and renderSheet() look the current screen up by its code key and stamp data-screen (and each listed part's
     data-name) on the page, so tests, the Atlas and notes read the ID straight off the screen. See MAINTAINING › Screen IDs.
   - Code keys: 'tab:<U.tab>', 'view:<U.view>' (Settings pages 'view:set/<U.setPg>', the Marks guide 'view:guide/<page>',
     where every mark's page is 'mark'), 'sheet:<U.sheet>', and 'overlay:<name>' for what's drawn outside render().
   - Append-only: a new screen takes the next number when it's built. Nothing is reused or renumbered; a screen that's
     removed stays, with status 'Retired in <version>'. Renaming a screen or moving its code changes only its line here.
   - parts: name (lower case with hyphens, what the part is) and sel (where it is, inside the screen). Notes write a part
     as 'VS-001 › start-session-button'. shared: parts named wherever they show (the tab bar, Back, a sheet's Close).
   - Public: screen names and code keys only, never personal data. */
